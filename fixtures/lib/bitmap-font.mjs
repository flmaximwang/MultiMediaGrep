/**
 * Row bitmaps (7 entries of 5-bit masks) for a single character, or `null`
 * when the font has no glyph for it. Lower case maps onto upper case.
 */
export function glyphRows(ch) {
  const upper = ch.toUpperCase();
  return Object.prototype.hasOwnProperty.call(GLYPHS, upper) ? GLYPHS[upper] : null;
}
